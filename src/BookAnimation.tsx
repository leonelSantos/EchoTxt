interface Props {
  /** 'large' for hero sections, 'small' for sidebars/widgets */
  size?: 'large' | 'small';
}

export function BookAnimation({ size = 'large' }: Props) {
  const [frameIndex, setFrameIndex] = useState(0);

  useEffect(() => {
    const [, holdMs] = FRAMES[frameIndex];
    const id = setTimeout(() => {
      setFrameIndex((i) => (i + 1) % FRAMES.length);
    }, holdMs);
    return () => clearTimeout(id);
  }, [frameIndex]);

  const [frame] = FRAMES[frameIndex];

  // Doubled from previous iteration: 4px -> 8px | 2.5px -> 5px
  const fontSize = size === 'large' ? '12px' : '8px';
  // Doubled from previous iteration: 40px -> 800px | 250px -> 500px
  const containerWidth = size === 'large' ? '1200px' : '700px';

  return (
    <div style={{ display: 'flex', justifyContent: 'left', margin: '20px 0' }}>
      <pre 
        className={`book-anim book-anim--${size}`} 
        aria-label="Animated flipping book"
        style={{
          fontFamily: "'Droid Sans Mono', monospace",
          lineHeight: '1.8', // Slightly adjusted for the larger scale
          whiteSpace: 'pre',
          fontSize: fontSize,
          textAlign: 'left',
          userSelect: 'none',
          backgroundColor: '#2a1f16',
          color: '#ffffff',
          padding: '25px',
          borderRadius: '8px',
          width: 'fit-content',
          maxWidth: containerWidth,
          overflow: 'hidden',
          boxShadow: '0 8px 12px rgba(0,0,0,0.4)'
        }}
      >
        {frame}
      </pre>
    </div>
  );
}